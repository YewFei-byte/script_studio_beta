// Copies the handful of Tabler icons the landing page sections use into
// shared/landing/icons.js, so published pages and the server never need the
// full 11 MB @tabler/icons package (a devDependency only).
// Run after changing the list: node scripts/build-landing-icons.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nodes = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/@tabler/icons/tabler-nodes-outline.json'), 'utf8'));

// Feature icons the AI may pick from (keep in sync with FEATURE_ICONS in schema.js),
// plus the UI glyphs the sections themselves use.
const ICONS = [
  'sparkles', 'shield-check', 'leaf', 'clock', 'heart', 'star', 'truck', 'message-circle', 'chart-bar',
  'circle-check', 'gift', 'world', 'bolt', 'users', 'tool', 'home', 'shopping-bag', 'calendar', 'map-pin',
  'phone', 'award', 'thumb-up', 'coin', 'rocket', 'lock', 'school', 'car', 'building-store', 'mail', 'photo',
  'brand-whatsapp', 'menu-2', 'x', 'chevron-down', 'player-play', 'arrow-right', 'check',
  'brand-facebook', 'brand-instagram', 'brand-youtube', 'brand-tiktok',
];

const toSvgInner = (n) =>
  n.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');

const lines = ICONS.map((name) => {
  if (!nodes[name]) throw new Error(`Unknown Tabler icon: ${name}`);
  return `  '${name}': '${toSvgInner(nodes[name])}',`;
});

fs.writeFileSync(
  path.join(root, 'shared/landing/icons.js'),
  `// GENERATED by scripts/build-landing-icons.mjs from @tabler/icons (MIT). Do not edit by hand.
// Outline icons, 24x24 viewBox, stroke = currentColor.

export const ICON_PATHS = {
${lines.join('\n')}
};

export function icon(name, { size = 24, className = '', label } = {}) {
  const inner = ICON_PATHS[name] || ICON_PATHS.sparkles;
  const a11y = label ? \`role="img" aria-label="\${label}"\` : 'aria-hidden="true"';
  return \`<svg class="ic \${className}" \${a11y} width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">\${inner}</svg>\`;
}
`
);
console.log(`Wrote ${ICONS.length} icons to shared/landing/icons.js`);
